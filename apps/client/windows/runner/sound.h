#ifndef RUNNER_SOUND_H_
#define RUNNER_SOUND_H_

// ============================================================
// 提示音
// ------------------------------------------------------------
// 新消息：短促一声，不打扰。
// 来电：循环响铃，直到接听/拒接/超时——这是「语音来电没有通知」
//      的核心：只有卡片没有声音，用户根本不知道有人在打进来。
//
// 为什么用 PlaySound + SND_ALIAS 而不是 MessageBox 的 MessageBeep：
//   MessageBeep 只弹一种系统默认音，无法循环，也无法停止。
//   PlaySound 支持 SND_LOOP | SND_ASYNC，且能一次调用停掉。
//
// 为什么用系统音频别名而不是自带 wav：
//   1. 不用往安装包里塞音频文件；
//   2. 跟随用户的「声音方案」——静音/专注助手生效时能自动安静，
//      这是系统级礼貌，自己做音量控制反而会盖过用户意图。
// ============================================================

/// 新消息提示音（单次，异步，不阻塞 UI）
void PlayMessageSound();

/// 开始循环响铃（来电）。重复调用不会叠加。
void StartRingtone();

/// 停止响铃
void StopRingtone();

/// 当前是否在响铃
bool IsRingtonePlaying();

#endif  // RUNNER_SOUND_H_
